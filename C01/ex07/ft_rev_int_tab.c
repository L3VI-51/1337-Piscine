void	ft_swap(int *a, int *b)
{
	int	tmp;

	tmp = *a;
	*a = *b;
	*b = tmp;
}

void	ft_rev_int_tab(int *tab, int size)
{
	int	i;
	int	l;

	i = 0;
	l = size - 1;
	while (i < l)
	{
		ft_swap(&tab[i], &tab[l]);
		l--;
		i++;
	}	
}
